import Foundation
import Testing
@testable import XdeskClipboard
import XdeskWire

@Suite struct ClipboardSyncTests {
    @Test func textCopiedOnAReachesB() async {
        let p = await Pair()
        p.boardA.copy(text("xin chào"))
        await p.a.poll()
        #expect(p.boardB.current?.text == "xin chào")
    }

    @Test func largeImageIsChunkedAndRebuilt() async {
        let p = await Pair()
        let big = png(extraBytes: 300_000)
        p.boardA.copy(big)
        await p.a.poll()
        #expect(p.boardB.current == big)
    }

    @Test func receivedItemIsNotEchoedBack() async {
        let p = await Pair()
        p.boardA.copy(text("một lần"))
        await p.a.poll()
        await p.b.poll()
        #expect(await p.toA.sentCount == 1)
        #expect(p.boardA.current?.text == "một lần")
    }

    @Test func concealedItemIsNeverSent() async {
        let p = await Pair()
        p.boardA.copy(text("mật khẩu"), types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])
        await p.a.poll()
        #expect(await p.toB.sentCount == 0)
        #expect(p.boardB.current == nil)
        #expect(await p.a.sendCurrent() == .nothingToSend)
    }

    @Test func autoGeneratedAndTransientAreNeverSent() async {
        let p = await Pair()
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            p.boardA.copy(text("x"), types: [type])
            await p.a.poll()
        }
        #expect(await p.toB.sentCount == 0)
    }

    @Test func senderWithPermissionOffSendsNothing() async {
        let p = await Pair(enabledA: false)
        p.boardA.copy(text("kín"))
        await p.a.poll()
        #expect(await p.a.sendCurrent() == .disabled)
        #expect(await p.toB.sentCount == 0)
    }

    @Test func receiverWithPermissionOffNeitherPullsNorWrites() async {
        let p = await Pair(enabledB: false)
        p.boardA.copy(text("không nhận"))
        await p.a.poll()
        #expect(await p.toA.sentCount == 0)
        #expect(p.boardB.current == nil)
        await p.b.handle(.clipData(ClipData(kind: .text, size: 1, hash: String(repeating: "0", count: 64))))
        await p.b.handleBulk([65])
        #expect(p.boardB.current == nil)
    }

    @Test func existingClipboardAtStartIsNotSent() async {
        let board = FakePasteboard()
        board.copy(text("có từ trước"))
        let t = LoopbackTransport()
        let sync = ClipboardSync(transport: t, pasteboard: board, isEnabled: { true })
        await sync.poll()
        #expect(await t.sentCount == 0)
    }

    @Test func recopyingReceivedContentAfterEchoWindowIsSentAgain() async {
        let boardA = FakePasteboard(), boardB = FakePasteboard()
        let toB = LoopbackTransport(), toA = LoopbackTransport()
        let a = ClipboardSync(transport: toB, pasteboard: boardA, echoWindow: .zero, isEnabled: { true })
        let b = ClipboardSync(transport: toA, pasteboard: boardB, echoWindow: .zero, isEnabled: { true })
        await toB.connect(to: b)
        await toA.connect(to: a)
        boardA.copy(text("cùng nội dung"))
        await a.poll()
        boardB.copy(text("cùng nội dung"))
        await b.poll()
        let offers = await toA.sent.filter { if case .clipOffer = $0 { true } else { false } }
        #expect(offers.count == 1)
    }

    @Test func thirdPartyRewriteRightAfterReceiveIsNotEchoed() async {
        let p = await Pair()
        p.boardA.copy(text("dội ngược"))
        await p.a.poll()
        p.boardB.copy(text("dội ngược"))   // trình quản lý clipboard chép lại ngay
        await p.b.poll()
        let offers = await p.toA.sent.filter { if case .clipOffer = $0 { true } else { false } }
        #expect(offers.isEmpty)
    }

    @Test func pullWithoutOfferSendsNothing() async {
        let p = await Pair()
        await p.a.handle(.clipPull(ClipPull(kind: .text)))
        #expect(await p.toB.sentCount == 0)
    }

    @Test func explicitSendWorksEvenForDuplicateContent() async {
        let p = await Pair()
        p.boardA.copy(text("lặp"))
        #expect(await p.a.sendCurrent() == .sent(.text))
        #expect(await p.a.sendCurrent() == .sent(.text))
        #expect(p.boardB.current?.text == "lặp")
    }
}
